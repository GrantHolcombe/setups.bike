-- 000_renumber_users.sql
-- Renumbers app_user.app_user_id to 1..N (keeping the current order) and updates every
-- table that points at it (bike, garage_order). Then resets the id counter to N+1.
--
-- Why: before 2026-11-13, AddUser's INSERT ... ON CONFLICT used up an id on every sign-in,
-- leaving gaps. That bug is fixed; this closes the gaps it left.
--
-- Run it twice with psql:
--   1. Dry run (rolls everything back):   psql ... -f db/migrations/000_renumber_users.sql
--   2. Apply (commits):                    psql ... -v apply=1 -f db/migrations/000_renumber_users.sql
--
-- Afterwards the JWT secret MUST be rotated: tokens carry the old ids and would otherwise
-- point at the wrong user.

\set ON_ERROR_STOP on

BEGIN;

-- Nobody signs in or adds a bike while this runs.
LOCK TABLE app_user, bike, garage_order IN ACCESS EXCLUSIVE MODE;

-- A bike whose app_user_id matches no user (the bike foreign key is NOT VALID, so these can
-- exist) could end up owned by someone else after renumbering. Stop if there are any.
DO $$
DECLARE orphans bigint;
BEGIN
  SELECT count(*) INTO orphans
    FROM bike b
   WHERE b.app_user_id IS NOT NULL
     AND NOT EXISTS (SELECT 1 FROM app_user u WHERE u.app_user_id = b.app_user_id);
  IF orphans > 0 THEN
    RAISE EXCEPTION 'Stopping: % bike(s) belong to a user id that does not exist. Fix those first.', orphans;
  END IF;
END $$;

CREATE TEMP TABLE user_id_map ON COMMIT DROP AS
SELECT app_user_id AS old_id,
       row_number() OVER (ORDER BY app_user_id) AS new_id
  FROM app_user;

CREATE TEMP TABLE counts_before ON COMMIT DROP AS
SELECT (SELECT count(*) FROM app_user)                       AS users,
       (SELECT count(*) FROM bike)                           AS bikes,
       (SELECT count(*) FROM garage_order)                   AS orders,
       (SELECT count(*) FROM bike WHERE app_user_id IS NULL) AS bikes_without_user;

-- Neither foreign key cascades, so drop them for the duration and put them back after.
ALTER TABLE bike         DROP CONSTRAINT fk_bike_app_user_id;
ALTER TABLE garage_order DROP CONSTRAINT fk_user_garage_order;

-- GENERATED ALWAYS columns can't be updated to a chosen value; allow it temporarily.
ALTER TABLE app_user ALTER COLUMN app_user_id SET GENERATED BY DEFAULT;

-- Two passes through negative numbers, so a new id never collides with an old one that
-- hasn't moved yet (the primary key is checked row by row).
UPDATE app_user u SET app_user_id = -m.new_id FROM user_id_map m WHERE u.app_user_id = m.old_id;
UPDATE app_user   SET app_user_id = -app_user_id;

-- A single UPDATE matches rows on their values from before the statement, so a bike that
-- moves from 5 to 3 is not then moved again by the 3 -> 2 mapping.
UPDATE bike         b SET app_user_id = m.new_id FROM user_id_map m WHERE b.app_user_id = m.old_id;
UPDATE garage_order g SET app_user_id = m.new_id FROM user_id_map m WHERE g.app_user_id = m.old_id;

ALTER TABLE app_user ALTER COLUMN app_user_id SET GENERATED ALWAYS;

-- Same constraints as before (the bike one was NOT VALID originally).
ALTER TABLE bike ADD CONSTRAINT fk_bike_app_user_id
  FOREIGN KEY (app_user_id) REFERENCES app_user(app_user_id) NOT VALID;
ALTER TABLE garage_order ADD CONSTRAINT fk_user_garage_order
  FOREIGN KEY (app_user_id) REFERENCES app_user(app_user_id);

-- Check nothing was lost or left behind; any failure rolls the whole thing back.
DO $$
DECLARE b record;
BEGIN
  SELECT * INTO b FROM counts_before;
  IF (SELECT count(*) FROM app_user) <> b.users
     OR (SELECT count(*) FROM bike) <> b.bikes
     OR (SELECT count(*) FROM garage_order) <> b.orders
     OR (SELECT count(*) FROM bike WHERE app_user_id IS NULL) <> b.bikes_without_user THEN
    RAISE EXCEPTION 'Row counts changed; rolling back.';
  END IF;
  IF (SELECT max(app_user_id) FROM app_user) <> b.users
     OR (SELECT min(app_user_id) FROM app_user) <> 1 THEN
    RAISE EXCEPTION 'User ids are not 1..N; rolling back.';
  END IF;
  IF EXISTS (SELECT 1 FROM bike x
              WHERE x.app_user_id IS NOT NULL
                AND NOT EXISTS (SELECT 1 FROM app_user u WHERE u.app_user_id = x.app_user_id)) THEN
    RAISE EXCEPTION 'A bike points at a missing user; rolling back.';
  END IF;
END $$;

-- Show the mapping (ids only, no names or emails).
SELECT old_id, new_id, old_id <> new_id AS changed FROM user_id_map ORDER BY new_id;

\if :{?apply}
  -- Next new user gets N+1. Only on apply: setval is NOT undone by ROLLBACK, so running it
  -- in a dry run would lower the counter while leaving the old ids in place.
  SELECT setval(pg_get_serial_sequence('public.app_user', 'app_user_id'),
                (SELECT max(app_user_id) FROM app_user));
  COMMIT;
  SELECT last_value AS id_counter_now FROM public.app_user_id_seq;
  \echo 'APPLIED: user ids renumbered. Now rotate the JWT secret.'
\else
  ROLLBACK;
  \echo 'DRY RUN ONLY: everything was rolled back. Re-run with -v apply=1 to apply.'
\endif
